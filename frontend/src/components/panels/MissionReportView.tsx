'use client';

import React, { useCallback, useEffect, useMemo, useState } from 'react';
import type { BriefingResponse, RouteComputeResponse, RouteStrategy } from '@/types';
import { STRATEGY_META } from '@/types';
import { getBriefing, getReportUrl } from '@/services/api';
import { AlertTriangle, Cpu, Download, ExternalLink, FileText, RefreshCw } from 'lucide-react';
import { withAlpha } from '@/utils/color';
import Markdown from '@/utils/markdown';

/**
 * Mission Report view.
 *
 * Two backend capabilities meet here:
 *
 *  1. GET /api/v1/report/briefing/{id}?strategy=… — a narrative Markdown
 *     briefing for one strategy, rendered inline.
 *  2. GET /api/v1/report/{id}?strategy=…&download=… — a complete,
 *     self-contained, print-optimised HTML document. That one is opened as a
 *     URL rather than fetched: it is already a finished document, and
 *     re-rendering it in React would only risk diverging from what a judge
 *     would print.
 *
 * Nothing in this view is computed client-side. The briefing text, the
 * strategy list and the generator attribution all come from the API.
 */

const STRATEGY_ORDER: RouteStrategy[] = ['SAFEST', 'FASTEST', 'SCIENCE_RICHEST', 'BALANCED'];

/** Preferred default when the user has not selected a strategy anywhere else. */
const DEFAULT_STRATEGY: RouteStrategy = 'BALANCED';

/**
 * How a generator is described to the reader.
 *
 * `template` is the deterministic, offline path — the normal one for a
 * demo with no external service reachable. It states exactly the same facts as
 * the model path, so it is labelled neutrally and never as a failure or a
 * degraded fallback.
 */
const GENERATOR_META: Record<string, { label: string; detail: string }> = {
  template: {
    label: 'Generated by deterministic template (offline)',
    detail:
      'A fixed generator rendered this text from the computed route metrics. '
      + 'No external service was contacted, and the same route always produces '
      + 'the same briefing.',
  },
  llm: {
    label: 'Generated by language model',
    detail:
      'A language model phrased this briefing from the computed route metrics. '
      + 'The figures it states come from the routing engine, not from the model.',
  },
};

interface MissionReportViewProps {
  routeResult: RouteComputeResponse | null;
  /** Strategy selected elsewhere in the app; used as the initial report subject. */
  activeStrategy: RouteStrategy | null;
}

export default function MissionReportView({
  routeResult,
  activeStrategy,
}: MissionReportViewProps) {
  /** Strategies this computation actually contains, in display order. */
  const available = useMemo<RouteStrategy[]>(() => {
    if (!routeResult) return [];
    return STRATEGY_ORDER.filter((s) => !!routeResult.strategies[s]);
  }, [routeResult]);

  const [picked, setPicked] = useState<RouteStrategy | null>(null);
  const [briefing, setBriefing] = useState<BriefingResponse | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  /**
   * Which strategy the report covers. Derived rather than stored, so the export
   * links always carry a strategy the computation actually contains — a stored
   * value would lag one render behind a new computation and briefly produce a
   * link to a strategy that is not there.
   *
   * Preference order: the user's explicit pick here, then the selection made
   * elsewhere in the app, then BALANCED, then whatever exists.
   */
  const strategy = useMemo<RouteStrategy | null>(() => {
    if (available.length === 0) return null;
    if (picked && available.includes(picked)) return picked;
    if (activeStrategy && available.includes(activeStrategy)) return activeStrategy;
    if (available.includes(DEFAULT_STRATEGY)) return DEFAULT_STRATEGY;
    return available[0];
  }, [picked, available, activeStrategy]);

  const computationId = routeResult?.computation_id ?? null;

  const loadBriefing = useCallback(() => {
    if (!computationId || !strategy) {
      setBriefing(null);
      return;
    }
    setLoading(true);
    setError(null);
    getBriefing(computationId, strategy)
      .then((res) => {
        setBriefing(res);
        setError(null);
      })
      .catch((e: unknown) => {
        setBriefing(null);
        setError(e instanceof Error ? e.message : 'Briefing request failed');
      })
      .finally(() => setLoading(false));
  }, [computationId, strategy]);

  useEffect(() => {
    loadBriefing();
  }, [loadBriefing]);

  const generatorMeta = briefing ? GENERATOR_META[briefing.generator] : null;

  return (
    <div
      className="flex-1 overflow-y-auto p-6"
      style={{ background: 'var(--surface)', color: 'var(--text-primary)' }}
    >
      {/* Page header */}
      <div className="mb-6">
        <p className="section-heading mb-1">Mission Documentation</p>
        <div className="flex items-center gap-3">
          <div
            className="w-10 h-10 rounded-xl flex items-center justify-center flex-shrink-0"
            style={{ background: 'var(--accent-light)', color: 'var(--accent)' }}
          >
            <FileText size={18} />
          </div>
          <h1 className="text-2xl font-bold" style={{ color: 'var(--text-primary)' }}>
            Mission Report
          </h1>
        </div>
      </div>

      {!routeResult || available.length === 0 ? (
        <div
          className="p-5 rounded-xl"
          style={{ background: 'var(--surface-raised)', border: '1px solid var(--border)' }}
        >
          <p className="text-sm font-semibold mb-2" style={{ color: 'var(--text-primary)' }}>
            Report generated after route computation
          </p>
          <p className="text-sm" style={{ color: 'var(--text-secondary)' }}>
            Plan a Marswalk to generate a mission briefing and an exportable report. The
            report covers the selected route&apos;s metrics, the four-strategy comparison,
            the route profile, science targets within range, and appendices documenting
            every data source and method used.
          </p>
        </div>
      ) : (
        <>
          {/* Strategy picker + export controls */}
          <div
            className="rounded-xl p-4 mb-5"
            style={{ background: 'var(--surface-raised)', border: '1px solid var(--border)' }}
          >
            <p className="section-heading mb-2">Report subject</p>
            <div className="flex flex-wrap gap-2 mb-4">
              {available.map((s) => {
                const meta = STRATEGY_META[s];
                const selected = strategy === s;
                return (
                  <button
                    key={s}
                    onClick={() => setPicked(s)}
                    className="flex items-center gap-2 px-3 py-1.5 rounded-lg text-xs font-medium transition-all"
                    style={{
                      background: selected
                        ? withAlpha(meta.color, 12)
                        : 'var(--surface)',
                      border: `1px solid ${
                        selected ? withAlpha(meta.color, 45) : 'var(--border)'
                      }`,
                      color: selected ? meta.color : 'var(--text-secondary)',
                    }}
                    aria-pressed={selected}
                  >
                    <span
                      aria-hidden
                      className="w-2.5 h-2.5 rounded-full"
                      style={{ background: meta.color }}
                    />
                    {meta.label}
                  </button>
                );
              })}
            </div>

            <p className="section-heading mb-2">Export</p>
            <div className="flex flex-wrap items-center gap-2">
              <a
                href={strategy ? getReportUrl(routeResult.computation_id, strategy, false) : '#'}
                target="_blank"
                rel="noopener noreferrer"
                className="flex items-center gap-2 px-3 py-2 rounded-lg text-xs font-semibold"
                style={{ background: 'var(--accent)', color: 'var(--on-accent)' }}
                title="Open the full mission report in a new tab. Print to PDF from there."
              >
                <ExternalLink size={13} />
                Open report
              </a>
              <a
                href={strategy ? getReportUrl(routeResult.computation_id, strategy, true) : '#'}
                target="_blank"
                rel="noopener noreferrer"
                className="flex items-center gap-2 px-3 py-2 rounded-lg text-xs font-semibold"
                style={{
                  background: 'var(--surface)',
                  border: '1px solid var(--border-strong)',
                  color: 'var(--text-primary)',
                }}
                title="Download the full mission report as a self-contained HTML file."
              >
                <Download size={13} />
                Download report
              </a>
              <span className="text-[10px] leading-snug" style={{ color: 'var(--text-muted)' }}>
                Self-contained, print-optimised HTML — briefing, four-strategy comparison,
                route profile, science targets, and data-provenance and method appendices.
              </span>
            </div>
          </div>

          {/* Briefing */}
          <div
            className="rounded-xl p-5"
            style={{ background: 'var(--surface-raised)', border: '1px solid var(--border)' }}
          >
            <div className="flex items-start justify-between gap-3 mb-3">
              <div>
                <h2 className="text-sm font-semibold" style={{ color: 'var(--text-primary)' }}>
                  Mission Briefing
                </h2>
                <p className="text-xs mt-0.5" style={{ color: 'var(--text-muted)' }}>
                  Computation <span className="font-mono">{routeResult.computation_id}</span>
                </p>
              </div>
              <button
                onClick={loadBriefing}
                disabled={loading}
                className="flex items-center gap-1.5 px-2.5 py-1.5 rounded text-[11px] font-medium disabled:opacity-40"
                style={{
                  background: 'var(--surface)',
                  border: '1px solid var(--border)',
                  color: 'var(--text-secondary)',
                }}
              >
                <RefreshCw size={11} className={loading ? 'animate-spin' : undefined} />
                Reload
              </button>
            </div>

            {/* Generator attribution — stated for every briefing, neutrally */}
            {briefing && (
              <div
                className="flex items-start gap-2 px-3 py-2 rounded-lg mb-4"
                style={{
                  background: 'var(--color-info-bg)',
                  border: '1px solid var(--color-info-border)',
                  color: 'var(--color-info)',
                }}
                title={generatorMeta?.detail}
              >
                <Cpu size={13} className="flex-shrink-0 mt-0.5" />
                <div>
                  <p className="text-[11px] font-semibold">
                    {generatorMeta?.label ?? `Generated by: ${briefing.generator}`}
                  </p>
                  <p className="text-[10px] mt-0.5 leading-relaxed">
                    {generatorMeta?.detail
                      ?? 'The backend did not describe this generator.'}
                    {briefing.cached && ' Served from the computation cache.'}
                  </p>
                </div>
              </div>
            )}

            {loading && !briefing && (
              <div className="space-y-2">
                <div className="skeleton h-5 w-1/2 rounded" />
                {[...Array(6)].map((_, i) => (
                  <div key={i} className="skeleton h-3 rounded" />
                ))}
              </div>
            )}

            {error && (
              <div
                className="flex items-start gap-2 p-3 rounded-lg"
                style={{
                  background: 'var(--color-danger-bg)',
                  border: '1px solid var(--color-danger-border)',
                  color: 'var(--color-danger)',
                }}
              >
                <AlertTriangle size={14} className="flex-shrink-0 mt-0.5" />
                <div>
                  <p className="text-xs font-semibold">Briefing unavailable</p>
                  <p className="text-[11px] mt-1 leading-relaxed">
                    No briefing is shown rather than a summary assembled in the browser —
                    the briefing must state only what the backend computed.
                  </p>
                  <p className="text-[10px] mt-1 font-mono opacity-80">{error}</p>
                </div>
              </div>
            )}

            {briefing && <Markdown text={briefing.briefing} />}
          </div>
        </>
      )}
    </div>
  );
}
